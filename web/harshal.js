"use strict";

const byId = id => document.getElementById(id);
const controls = byId("controls");
const runButton = byId("run-button");
const statusText = byId("status");
const resultsBody = byId("results-body");
const canvas = byId("map-canvas");
const context = canvas.getContext("2d");
const palette = ["#c9dce9", "#f3dac1", "#d1e4c5", "#e2cfea", "#f2e9b8", "#c5e6e5", "#e6cdca", "#d8dbe1"];
let scene = null;
let comparison = null;
let busy = false;

// Python performs both searches. JavaScript sends selections and draws results.
function options() {
    return {
        kind: byId("kind").value,
        size: Number(byId("size").value),
        seed: Number(byId("seed").value),
        start: byId("start").value,
        goal: byId("goal").value,
        scenario: byId("scenario").value
    };
}

function setBusy(value) {
    busy = value;
    for (const input of controls.querySelectorAll("select, input, button")) input.disabled = value;
    runButton.disabled = value || !scene;
}

function status(message, error = false) {
    statusText.textContent = message;
    statusText.classList.toggle("error", error);
}

function resetResults() {
    comparison = null;
    resultsBody.innerHTML = '<tr><td colspan="3">Run a comparison to see measured results.</td></tr>';
    byId("validation").textContent = "";
    byId("scenario-note").textContent = "";
}

async function request(url, settings) {
    const response = await fetch(url, settings);
    const data = await response.json();
    if (!response.ok) throw new Error(data.error || `Request failed (${response.status}).`);
    return data;
}

// A scene supplies coordinates and node indices matching the route responses.
async function loadScene() {
    if (busy) return;
    const road = byId("kind").value === "road";
    if (road && !byId("seed").checkValidity()) byId("seed").value = "0";
    if (!controls.reportValidity()) return;
    const selected = options();
    resetResults();
    scene = null;
    setBusy(true);
    status("Loading map...");
    byId("map-status").textContent = "Loading network...";
    context.clearRect(0, 0, canvas.width, canvas.height);
    document.querySelectorAll(".road-control").forEach(el => { el.hidden = !road; });
    document.querySelectorAll(".grid-control").forEach(el => { el.hidden = road; });
    const hubScenario = byId("scenario").querySelector('[value="hub"]');
    hubScenario.hidden = !road;
    hubScenario.disabled = !road;
    if (!road && byId("scenario").value === "hub") byId("scenario").value = "none";
    byId("map-title").textContent = road ? "Road map" : "Obstacle grid";
    byId("data-credit").innerHTML = road
        ? 'Road data: <a href="https://www.openstreetmap.org/copyright">© OpenStreetMap contributors</a> · local jumeirah.osm file.'
        : "Synthetic obstacle grid generated by the project code. Dark cells are obstacles; costs are measured in moves.";
    try {
        const query = new URLSearchParams({ kind: selected.kind, size: selected.size, seed: selected.seed });
        scene = await request(`/api/scene?${query}`);
        if (road) {
            for (const id of ["start", "goal"]) {
                const select = byId(id);
                const previous = select.value;
                select.replaceChildren(...scene.hubs.map(hub => new Option(hub.name, hub.name)));
                if (scene.hubs.some(hub => hub.name === previous)) select.value = previous;
            }
        }
        byId("map-status").textContent = `${scene.node_count.toLocaleString()} nodes · ${scene.directed_edge_count.toLocaleString()} directed connections · ${scene.region_labels.length} regions`;
        drawMap();
        status("Map ready. Choose a scenario and run the comparison.");
    } catch (error) {
        scene = null;
        byId("map-status").textContent = "Map could not load.";
        status(`Error: ${error.message} Check that the Python demo server is running, then refresh.`, true);
    } finally {
        setBusy(false);
    }
}

function endpoint(id) {
    if (scene.kind === "grid") return scene[id];
    return scene.hubs.find(hub => hub.name === byId(id).value)?.node;
}

// Fit coordinates onto the canvas without changing the map's proportions.
function drawMap() {
    if (!scene) return;
    let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
    for (const [x, y] of scene.nodes) {
        minX = Math.min(minX, x); maxX = Math.max(maxX, x);
        minY = Math.min(minY, y); maxY = Math.max(maxY, y);
    }
    const grid = scene.kind === "grid";
    if (grid) { minX = 0; minY = 0; maxX = scene.size; maxY = scene.size; }
    const margin = grid ? 28 : 50;
    const scale = Math.min((canvas.width - margin * 2) / Math.max(1, maxX - minX), (canvas.height - margin * 2) / Math.max(1, maxY - minY));
    const offsetX = (canvas.width - (maxX - minX) * scale) / 2;
    const offsetY = (canvas.height - (maxY - minY) * scale) / 2;
    const point = index => {
        const [x, y] = scene.nodes[index];
        return [offsetX + (x - minX) * scale, canvas.height - offsetY - (y - minY) * scale];
    };
    const segment = (a, b) => {
        context.moveTo(...point(a)); context.lineTo(...point(b));
    };
    context.clearRect(0, 0, canvas.width, canvas.height);
    context.fillStyle = "#ffffff";
    context.fillRect(0, 0, canvas.width, canvas.height);
    const regions = byId("show-regions").checked;
    if (grid) {
        context.fillStyle = "#293e4a";
        context.fillRect(offsetX, offsetY, scene.size * scale, scene.size * scale);
        for (let i = 0; i < scene.nodes.length; i++) {
            const [x, y] = point(i);
            context.fillStyle = regions ? palette[scene.nodes[i][2] % palette.length] : "#f7fafc";
            context.fillRect(x - scale / 2 + .25, y - scale / 2 + .25, scale - .5, scale - .5);
        }
    } else {
        context.strokeStyle = "#bcc9d1";
        context.lineWidth = .75;
        context.beginPath();
        for (const [a, b] of scene.edges) segment(a, b);
        context.stroke();
        if (regions) {
            for (let i = 0; i < scene.nodes.length; i++) {
                const [x, y] = point(i);
                context.fillStyle = palette[scene.nodes[i][2] % palette.length];
                context.fillRect(x - 1, y - 1, 2, 2);
            }
        }
    }
    // Trace points show actual detailed-node expansions, rather than an animation estimate.
    if (comparison && byId("show-explored").checked) {
        for (const [result, color] of [[comparison.flat, "#1474b866"], [comparison.tier, "#e7831966"]]) {
            context.fillStyle = color;
            for (const index of result.trace) {
                const [x, y] = point(index);
                const width = grid ? Math.max(2, scale * .45) : 2.3;
                context.fillRect(x - width / 2, y - width / 2, width, width);
            }
        }
    }
    context.lineCap = "round";
    context.lineJoin = "round";
    if (comparison) {
        // A wide blue path and narrow dashed orange path remain visible when overlapping.
        for (const [result, color, width, dash] of [[comparison.flat, "#1474b8", 6, []], [comparison.tier, "#e78319", 3, [9, 6]]]) {
            context.strokeStyle = color;
            context.lineWidth = grid ? Math.min(width, Math.max(1.5, scale * .55)) : width;
            context.setLineDash(dash);
            context.beginPath();
            result.path.forEach((node, i) => { if (i) segment(result.path[i - 1], node); });
            context.stroke();
        }
        context.setLineDash([]);
        context.strokeStyle = "#cb21aa";
        context.lineWidth = grid ? Math.max(2, scale * .16) : 4;
        context.beginPath();
        for (const [a, b] of comparison.blocked) segment(a, b);
        context.stroke();
    }
    if (!grid) {
        context.font = "12px Arial";
        for (const hub of scene.hubs) {
            const [x, y] = point(hub.node);
            context.beginPath(); context.arc(x, y, 4, 0, Math.PI * 2);
            context.fillStyle = "white"; context.fill();
            context.strokeStyle = "#17384b"; context.lineWidth = 1.5; context.stroke();
            const labelX = Math.min(canvas.width - context.measureText(hub.name).width - 8, x + 10);
            context.strokeStyle = "white"; context.lineWidth = 4;
            context.strokeText(hub.name, labelX, y - 8);
            context.fillStyle = "#17384b"; context.fillText(hub.name, labelX, y - 8);
        }
    }
    const start = comparison?.start ?? endpoint("start");
    const goal = comparison?.goal ?? endpoint("goal");
    const markers = start === goal ? [[start, "S/G", "#167347"]] : [[start, "S", "#167347"], [goal, "G", "#a62f40"]];
    for (const [index, label, color] of markers) {
        if (index == null) continue;
        const [x, y] = point(index);
        context.beginPath(); context.arc(x, y, label === "S/G" ? 11 : 8, 0, Math.PI * 2);
        context.fillStyle = color; context.fill();
        context.strokeStyle = "white"; context.lineWidth = 2; context.stroke();
        context.font = "bold 10px Arial"; context.textAlign = "center"; context.textBaseline = "middle";
        context.fillStyle = "white"; context.fillText(label, x, y);
        context.textAlign = "start"; context.textBaseline = "alphabetic";
    }
}

// These values come directly from Python, including for unsuccessful searches.
function showResults(result) {
    const cost = item => item.found ? item.cost.toFixed(1) : "No route";
    const row = (name, flat, tier) => `<tr><td>${name}</td><td>${flat}</td><td>${tier}</td></tr>`;
    resultsBody.innerHTML = [
        row(`Distance (${result.unit})`, cost(result.flat), cost(result.tier)),
        row("Detailed node expansions", result.flat.nodes, result.tier.nodes),
        row("Abstract node expansions", result.flat.abstract_nodes, result.tier.abstract_nodes),
        row("Total node expansions", result.flat.total_nodes, result.tier.total_nodes),
        row("Query time (ms)", result.flat.runtime_ms.toFixed(2), result.tier.runtime_ms.toFixed(2)),
        row("Region preparation time (ms)", "—", result.tier.preprocess_ms.toFixed(2)),
        row("Search mode", result.flat.mode, result.tier.mode),
        row("Detailed search attempts", result.flat.attempts, result.tier.attempts)
    ].join("");
    byId("scenario-note").textContent = `${result.scenario_note} Closed directed connections: ${result.blocked_count}.`;
    byId("validation").textContent = result.verified ? result.validation : "Validation was not confirmed.";
    if (!result.flat.found || !result.tier.found) {
        status("No route found for this scenario. The map shows the closed connections.");
    } else if (result.flat.cost > 0) {
        const extra = Math.max(0, (result.tier.cost / result.flat.cost - 1) * 100);
        status(`Comparison complete. Two-tier route: ${extra.toFixed(1)}% longer than the verified flat A* route.`);
    } else {
        status("Start and destination are the same. Route distance is zero.");
    }
}

controls.addEventListener("submit", async event => {
    event.preventDefault();
    if (busy || !scene) return;
    setBusy(true);
    resetResults();
    drawMap();
    status("Running both searches and validating their routes...");
    try {
        comparison = await request("/api/run", {
            method: "POST", headers: { "Content-Type": "application/json" },
            body: JSON.stringify(options())
        });
        showResults(comparison);
        drawMap();
    } catch (error) {
        status(`Error: ${error.message}`, true);
    } finally {
        setBusy(false);
    }
});

for (const id of ["kind", "size", "seed"]) byId(id).addEventListener("change", loadScene);
for (const id of ["start", "goal", "scenario"]) byId(id).addEventListener("change", () => {
    resetResults(); drawMap(); status("Selection changed. Run comparison to update the results.");
});
for (const id of ["show-regions", "show-explored"]) byId(id).addEventListener("change", drawMap);

loadScene();
